// fullFold returns the full case fold of a single rune. Runes with no entry in
// the exception table fold exactly as strings.ToLower folds them, which is what
// makes the table small: it holds only where the two disagree.
//
// The exception table is consulted first and returned as-is; otherwise the
// baseline is unicode.ToLower, not the rune unchanged -- ordinary ASCII and the
// vast majority of Unicode letters have no entry in the table at all and still
// need to be lowercased for a case-insensitive match to work.
func fullFold(r rune) string {
	if folded, ok := fullFoldExceptions[r]; ok {
		return folded
	}
	return string(unicode.ToLower(r))
}
